package com.cardosama.fontawesome_fx_6;

/**
 * Énumération des différents types de polices FontAwesome disponibles.
 * <p>
 * Chaque type correspond à un fichier de police distinct et à un style visuel
 * spécifique des icônes.
 * <p>
 * Auteur : Cardo Sama
 * Version : 1.1
 */
public enum FontAwesomeType {
    /**
     * Style solid (plein). Icônes avec remplissage complet
     */
    SOLID,

    /**
     * Style regular (régulier). Icônes avec contours
     */
    REGULAR,

    /**
     * Style brand (marque). Logos et icônes de marques
     */
    BRAND,

    /**
     * Style light (léger) - Version plus fine que regular
     */
    LIGHT,

    /**
     * Style thin (fin) - Version la plus fine des icônes
     */
    THIN,

    /**
     * Style duotone (deux tons). Icônes avec deux niveaux d'opacité
     */
    DUOTONE
}
